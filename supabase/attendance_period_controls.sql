begin;

create table if not exists public.employee_attendance_period_control (
  branch_id uuid not null references public.branch(id) on delete cascade,
  period_start date not null,
  period_end date not null,
  is_locked boolean not null,
  updated_by_tafi_admin_id uuid references public.tafi_admin(id) on delete set null,
  updated_at timestamptz not null default now(),
  primary key (branch_id, period_start),
  check (period_start <= period_end)
);

alter table public.employee_attendance_period_control enable row level security;
revoke all on table public.employee_attendance_period_control from public, anon, authenticated;

create table if not exists public.employee_attendance_period_unlock_request (
  id bigint generated by default as identity primary key,
  branch_id uuid not null references public.branch(id) on delete cascade,
  period_start date not null,
  period_end date not null,
  requested_by_branch_admin_id uuid not null
    references public.branch_admin(id) on delete cascade,
  requested_at timestamptz not null default now(),
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'denied')),
  resolved_by_tafi_admin_id uuid references public.tafi_admin(id) on delete set null,
  resolved_at timestamptz,
  check (period_start <= period_end)
);

create unique index if not exists employee_attendance_period_unlock_request_pending_idx
  on public.employee_attendance_period_unlock_request (branch_id, period_start)
  where status = 'pending';
create index if not exists employee_attendance_period_unlock_request_period_idx
  on public.employee_attendance_period_unlock_request (branch_id, period_start, requested_at desc);

alter table public.employee_attendance_period_unlock_request enable row level security;
revoke all on table public.employee_attendance_period_unlock_request from public, anon, authenticated;

create or replace function public.attendance_period_bounds(p_attendance_date date)
returns table (start_date date, end_date date)
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_month_start date;
  v_month_end date;
  v_first_day_of_week integer;
  v_first_period_end date;
  v_period_start date;
  v_period_end date;
begin
  if p_attendance_date is null then
    raise exception 'Attendance date is required';
  end if;

  v_month_start := date_trunc('month', p_attendance_date)::date;
  v_month_end := (v_month_start + interval '1 month - 1 day')::date;
  v_first_day_of_week := extract(dow from v_month_start)::integer;

  if v_first_day_of_week <> 0 then
    v_first_period_end := least(
      v_month_start + (6 - v_first_day_of_week),
      v_month_end
    );
    if p_attendance_date <= v_first_period_end then
      return query select v_month_start, v_first_period_end;
      return;
    end if;
    v_period_start := v_first_period_end + 1;
  else
    v_period_start := v_month_start;
  end if;

  loop
    v_period_end := v_period_start + 6;
    if v_period_end <= v_month_end then
      if p_attendance_date <= v_period_end then
        return query select v_period_start, v_period_end;
        return;
      end if;
      v_period_start := v_period_end + 1;
    else
      return query select v_period_start, v_month_end;
      return;
    end if;
  end loop;
end;
$$;

create or replace function public.attendance_period_lock_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_branch_id uuid;
  v_period_start date;
  v_period_end date;
  v_manual_lock boolean;
begin
  if new.submitted_by is null then
    return new;
  end if;

  select employee.branch_id
  into v_branch_id
  from public.employee as employee
  where employee.id = new.employee_id;

  select bounds.start_date, bounds.end_date
  into v_period_start, v_period_end
  from public.attendance_period_bounds(new.attendance_date) as bounds;

  select control.is_locked
  into v_manual_lock
  from public.employee_attendance_period_control as control
  where control.branch_id = v_branch_id
    and control.period_start = v_period_start;

  if coalesce(v_manual_lock, v_period_end < timezone('Asia/Manila', now())::date) then
    raise exception 'This attendance period is locked. Request TAFI Admin to unlock it.'
      using errcode = '55000';
  end if;

  return new;
end;
$$;

drop trigger if exists employee_attendance_period_lock_guard
  on public.employee_attendance;
create trigger employee_attendance_period_lock_guard
before insert or update on public.employee_attendance
for each row execute function public.attendance_period_lock_guard();

create or replace function public.branch_admin_get_attendance_period_control(
  p_session_token uuid,
  p_attendance_date date
)
returns table (
  period_start date,
  period_end date,
  is_locked boolean,
  is_automatic boolean,
  pending_request_id bigint,
  requested_by text,
  requested_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_branch_id uuid;
  v_period_start date;
  v_period_end date;
begin
  select branch_admin.branch_id
  into v_branch_id
  from public.branch_admin_session as admin_session
  join public.branch_admin as branch_admin
    on branch_admin.id = admin_session.branch_admin_id
  where admin_session.session_token = p_session_token
    and admin_session.expires_at > now();

  if not found then
    raise exception 'Branch Admin session is invalid or expired' using errcode = '28000';
  end if;

  select bounds.start_date, bounds.end_date
  into v_period_start, v_period_end
  from public.attendance_period_bounds(p_attendance_date) as bounds;

  return query
  select v_period_start,
    v_period_end,
    coalesce(control.is_locked, v_period_end < timezone('Asia/Manila', now())::date),
    control.branch_id is null,
    request.id,
    branch_admin.name,
    request.requested_at
  from (select 1) as anchor
  left join public.employee_attendance_period_control as control
    on control.branch_id = v_branch_id
    and control.period_start = v_period_start
  left join lateral (
    select unlock_request.id,
      unlock_request.requested_by_branch_admin_id,
      unlock_request.requested_at
    from public.employee_attendance_period_unlock_request as unlock_request
    where unlock_request.branch_id = v_branch_id
      and unlock_request.period_start = v_period_start
      and unlock_request.status = 'pending'
    order by unlock_request.requested_at desc
    limit 1
  ) as request on true
  left join public.branch_admin as branch_admin
    on branch_admin.id = request.requested_by_branch_admin_id;
end;
$$;

create or replace function public.branch_admin_request_attendance_period_unlock(
  p_session_token uuid,
  p_attendance_date date
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_branch_admin_id uuid;
  v_branch_id uuid;
  v_period_start date;
  v_period_end date;
  v_request_id bigint;
begin
  select branch_admin.id, branch_admin.branch_id
  into v_branch_admin_id, v_branch_id
  from public.branch_admin_session as admin_session
  join public.branch_admin as branch_admin
    on branch_admin.id = admin_session.branch_admin_id
  where admin_session.session_token = p_session_token
    and admin_session.expires_at > now();

  if not found then
    raise exception 'Branch Admin session is invalid or expired' using errcode = '28000';
  end if;

  select bounds.start_date, bounds.end_date
  into v_period_start, v_period_end
  from public.attendance_period_bounds(p_attendance_date) as bounds;

  if not coalesce((
    select control.is_locked
    from public.employee_attendance_period_control as control
    where control.branch_id = v_branch_id
      and control.period_start = v_period_start
  ), v_period_end < timezone('Asia/Manila', now())::date) then
    raise exception 'This attendance period is already unlocked';
  end if;

  insert into public.employee_attendance_period_unlock_request (
    branch_id, period_start, period_end, requested_by_branch_admin_id
  )
  values (v_branch_id, v_period_start, v_period_end, v_branch_admin_id)
  on conflict (branch_id, period_start) where status = 'pending'
  do update set
    requested_by_branch_admin_id = excluded.requested_by_branch_admin_id,
    requested_at = now()
  returning id into v_request_id;

  return v_request_id;
end;
$$;

create or replace function public.tafi_admin_list_attendance_period_controls(
  p_session_token uuid,
  p_branch_id uuid,
  p_period_starts jsonb
)
returns table (
  period_start date,
  period_end date,
  is_locked boolean,
  is_automatic boolean,
  pending_request_id bigint,
  requested_by text,
  requested_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_admin_id uuid;
  v_requested_start date;
  v_period_start date;
  v_period_end date;
begin
  select admin_session.tafi_admin_id
  into v_admin_id
  from public.tafi_admin_session as admin_session
  where admin_session.session_token = p_session_token
    and admin_session.expires_at > now();

  if not found then
    raise exception 'Invalid or expired TAFI Admin session' using errcode = '28000';
  end if;
  if p_branch_id is null
    or not exists (select 1 from public.branch where id = p_branch_id)
    or jsonb_typeof(p_period_starts) is distinct from 'array' then
    raise exception 'A valid branch and array of attendance period starts are required';
  end if;

  for v_requested_start in
    select period_start.value::date
    from jsonb_array_elements_text(p_period_starts) as period_start(value)
  loop
    select bounds.start_date, bounds.end_date
    into v_period_start, v_period_end
    from public.attendance_period_bounds(v_requested_start) as bounds;

    if v_period_start <> v_requested_start then
      raise exception 'Invalid attendance period start date';
    end if;

    return query
    select v_period_start,
      v_period_end,
      coalesce(control.is_locked, v_period_end < timezone('Asia/Manila', now())::date),
      control.branch_id is null,
      request.id,
      branch_admin.name,
      request.requested_at
    from (select 1) as anchor
    left join public.employee_attendance_period_control as control
      on control.branch_id = p_branch_id
      and control.period_start = v_period_start
    left join lateral (
      select unlock_request.id,
        unlock_request.requested_by_branch_admin_id,
        unlock_request.requested_at
      from public.employee_attendance_period_unlock_request as unlock_request
      where unlock_request.branch_id = p_branch_id
        and unlock_request.period_start = v_period_start
        and unlock_request.status = 'pending'
      order by unlock_request.requested_at desc
      limit 1
    ) as request on true
    left join public.branch_admin as branch_admin
      on branch_admin.id = request.requested_by_branch_admin_id;
  end loop;
end;
$$;

create or replace function public.tafi_admin_set_attendance_period_lock(
  p_session_token uuid,
  p_branch_id uuid,
  p_period_start date,
  p_period_end date,
  p_is_locked boolean
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_admin_id uuid;
  v_expected_start date;
  v_expected_end date;
begin
  select admin_session.tafi_admin_id
  into v_admin_id
  from public.tafi_admin_session as admin_session
  where admin_session.session_token = p_session_token
    and admin_session.expires_at > now();

  if not found then
    raise exception 'Invalid or expired TAFI Admin session' using errcode = '28000';
  end if;
  if p_branch_id is null
    or p_period_start is null
    or p_period_end is null
    or p_is_locked is null
    or not exists (select 1 from public.branch where id = p_branch_id) then
    raise exception 'A valid branch, period, and lock status are required';
  end if;

  select bounds.start_date, bounds.end_date
  into v_expected_start, v_expected_end
  from public.attendance_period_bounds(p_period_start) as bounds;
  if v_expected_start <> p_period_start or v_expected_end <> p_period_end then
    raise exception 'Attendance period dates do not match a valid payroll period';
  end if;

  insert into public.employee_attendance_period_control (
    branch_id, period_start, period_end, is_locked, updated_by_tafi_admin_id, updated_at
  )
  values (p_branch_id, p_period_start, p_period_end, p_is_locked, v_admin_id, now())
  on conflict (branch_id, period_start) do update
  set period_end = excluded.period_end,
    is_locked = excluded.is_locked,
    updated_by_tafi_admin_id = excluded.updated_by_tafi_admin_id,
    updated_at = now();

  update public.employee_attendance_period_unlock_request as request
  set status = case when p_is_locked then 'denied' else 'approved' end,
    resolved_by_tafi_admin_id = v_admin_id,
    resolved_at = now()
  where request.branch_id = p_branch_id
    and request.period_start = p_period_start
    and request.status = 'pending';

  return true;
end;
$$;

revoke all on function public.attendance_period_bounds(date) from public;
